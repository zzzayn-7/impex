"""Where uploaded company logos live.

A small abstraction so the files can live in different places without touching the rest of the service: implement `LogoStorage` and return it from
`get_logo_storage`. Two implementations ship:
  * `LocalLogoStorage` (the default): a directory (`LOGO_STORAGE_DIR`, default `/data/logos`) that docker-compose mounts as a NAMED VOLUME, so logos survive
    container restarts, redeployments and `docker compose down` (only `down -v` would remove them, as for the databases);
  * `BlobLogoStorage`: a Vercel Blob store, for deployments on Vercel where a function has no persistent disk. Selected with `LOGO_STORAGE=blob` (and
    automatically on Vercel when nothing is set). The store is PRIVATE by default (`LOGO_BLOB_ACCESS`, which must match the store's access mode): a logo
    is never reachable by a public address, only through this service's own authenticated route. The credential (`BLOB_READ_WRITE_TOKEN`, or the OIDC
    variables Vercel adds when a store is connected) is read by the SDK from the environment.

Safety rules, enforced here and nowhere else:
  * keys are generated by the server (random, unpredictable) and re-validated against a strict pattern on every use, so a key
    read from the database or anywhere else can never escape the storage directory;
  * writes are atomic (temp file, fsync, rename): a reader never sees half a file and a crash leaves no partial logo;
  * a stored file is never exposed by path: callers get bytes through `read`, and the HTTP layer decides what to send.
"""
import os
import re
import secrets
import tempfile
from pathlib import Path
from typing import Optional, Protocol

KEY_PATTERN = re.compile(r"^[a-z0-9]{2}/[A-Za-z0-9_-]{32,64}\.png$")


class StorageError(RuntimeError):
    """The storage could not complete the operation (full disk, missing volume, permissions...)."""


def _new_key() -> str:
    token = secrets.token_urlsafe(32)  # 43 characters of CSPRNG output
    return f"{token[:2].lower() if token[:2].isalnum() else 'aa'}/{token}.png"


class LogoStorage(Protocol):
    def new_key(self) -> str: ...

    def write(self, key: str, data: bytes) -> None: ...

    def read(self, key: str) -> Optional[bytes]: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None: ...


class LocalLogoStorage:
    def __init__(self, root: str) -> None:
        self.root = Path(root)

    def new_key(self) -> str:
        return _new_key()

    def _path(self, key: str) -> Path:
        if not isinstance(key, str) or not KEY_PATTERN.match(key):
            raise StorageError("invalid storage key")
        path = (self.root / key).resolve()
        if self.root.resolve() not in path.parents:
            raise StorageError("invalid storage key")
        return path

    def write(self, key: str, data: bytes) -> None:
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, temp_name = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
            try:
                with os.fdopen(fd, "wb") as handle:
                    handle.write(data)
                    handle.flush()
                    os.fsync(handle.fileno())
                os.replace(temp_name, path)
            except BaseException:
                try:
                    os.unlink(temp_name)
                except OSError:
                    pass
                raise
        except OSError as exc:
            raise StorageError(f"could not store the logo: {exc.__class__.__name__}") from exc

    def read(self, key: str) -> Optional[bytes]:
        path = self._path(key)
        try:
            return path.read_bytes()
        except FileNotFoundError:
            return None
        except OSError as exc:
            raise StorageError(f"could not read the logo: {exc.__class__.__name__}") from exc

    def exists(self, key: str) -> bool:
        try:
            return self._path(key).is_file()
        except OSError as exc:
            raise StorageError(f"could not check the logo: {exc.__class__.__name__}") from exc

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError:
            pass  # a leftover file is harmless: nothing refers to it and its name is unguessable


class BlobLogoStorage:
    """Logos in a Vercel Blob store. Same contract and the same key rules as the local storage; the object name is `logos/<key>`."""

    PREFIX = "logos/"

    def __init__(self, access: str = "private", client=None) -> None:
        if access not in ("private", "public"):
            raise StorageError("LOGO_BLOB_ACCESS must be 'private' or 'public'")
        self.access = access
        self._client = client  # a module offering put_blob / get_blob / head_blob / delete_blob (the SDK's sync API); tests pass a fake

    def _blob(self):
        if self._client is None:
            try:
                from vercel.blob import sync as blob  # imported on first use: the local storage needs no SDK
            except ImportError as exc:  # pragma: no cover - the SDK is in requirements.txt
                raise StorageError("the Vercel Blob SDK is not installed") from exc
            self._client = blob
        return self._client

    def new_key(self) -> str:
        return _new_key()  # the same unpredictable key format as the local storage

    def _name(self, key: str) -> str:
        if not isinstance(key, str) or not KEY_PATTERN.match(key):
            raise StorageError("invalid storage key")
        return self.PREFIX + key

    def _not_found(self, exc: BaseException) -> bool:
        return isinstance(exc, FileNotFoundError) or exc.__class__.__name__ == "BlobNotFoundError"

    def write(self, key: str, data: bytes) -> None:
        name = self._name(key)
        try:
            self._blob().put_blob(name, data, access=self.access, content_type="image/png", add_random_suffix=False, allow_overwrite=True)
        except StorageError:
            raise
        except Exception as exc:
            raise StorageError(f"could not store the logo: {exc.__class__.__name__}") from exc

    def read(self, key: str) -> Optional[bytes]:
        name = self._name(key)
        try:
            return bytes(self._blob().get_blob(name, access=self.access).body)
        except StorageError:
            raise
        except Exception as exc:
            if self._not_found(exc):
                return None
            raise StorageError(f"could not read the logo: {exc.__class__.__name__}") from exc

    def exists(self, key: str) -> bool:
        name = self._name(key)
        try:
            self._blob().head_blob(name)
            return True
        except StorageError:
            raise
        except Exception as exc:
            if self._not_found(exc):
                return False
            raise StorageError(f"could not check the logo: {exc.__class__.__name__}") from exc

    def delete(self, key: str) -> None:
        try:
            self._blob().delete_blob(self._name(key))
        except Exception:
            pass  # a leftover object is harmless: nothing refers to it and its name is unguessable


def get_logo_storage() -> LogoStorage:
    """FastAPI dependency; tests override it with a temporary directory."""
    mode = os.getenv("LOGO_STORAGE", "blob" if os.getenv("VERCEL") else "local").strip().lower()
    if mode == "blob":
        return BlobLogoStorage(access=os.getenv("LOGO_BLOB_ACCESS", "private").strip().lower())
    return LocalLogoStorage(os.getenv("LOGO_STORAGE_DIR", "/data/logos"))
